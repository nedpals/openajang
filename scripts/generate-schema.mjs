import { readFile, writeFile } from 'node:fs/promises';

const source = new URL('../schema/0.1/event.json', import.meta.url);
const target = new URL('../packages/core/src/schema.ts', import.meta.url);
const schema = JSON.parse(await readFile(source, 'utf8'));
await writeFile(target, `// Generated by scripts/generate-schema.mjs.\nexport const EVENT_SCHEMA = ${JSON.stringify(schema, null, 2)} as const;\nexport const SCHEMA_ID: string = EVENT_SCHEMA.$id;\n`);
