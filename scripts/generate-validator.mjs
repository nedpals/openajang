import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import Ajv2020Pkg from 'ajv/dist/2020.js';
import standalone from 'ajv/dist/standalone/index.js';
import { _ } from 'ajv/dist/compile/codegen/index.js';
import { build } from 'esbuild';

const root = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(root, '..');
const schemaPath = path.join(repo, 'schema/0.1/event.json');
const coreSrc = path.join(repo, 'packages/core/src');
const targetPath = path.join(coreSrc, 'validator.generated.ts');
const checkOnly = process.argv.includes('--check');

const schema = JSON.parse(await readFile(schemaPath, 'utf8'));

/** Collect the oa-* custom formats the schema actually uses. */
function collectFormats(value, found = new Set()) {
  if (Array.isArray(value)) {
    for (const item of value) collectFormats(item, found);
  } else if (value && typeof value === 'object') {
    if (typeof value.format === 'string' && value.format.startsWith('oa-')) found.add(value.format);
    for (const item of Object.values(value)) collectFormats(item, found);
  }
  return found;
}

const formatNames = [...collectFormats(schema)].sort();
const Ajv2020 = Ajv2020Pkg.default || Ajv2020Pkg;
const ajv = new Ajv2020({
  allErrors: true,
  strict: false,
  // `__formatsRef.value` is a local object lookup, not an ESM namespace access,
  // so bundlers cannot mistake the computed format names for missing exports.
  code: { source: true, esm: true, formats: _`__formatsRef.value` }
});

for (const name of formatNames) {
  // Placeholder definitions: the generated module references the real
  // implementations in formats.ts through the `__formats` import below.
  ajv.addFormat(name, { type: 'string', validate: () => true, async: false });
}

const standaloneCode = standalone(ajv, ajv.compile(schema));
const entry = [
  "import { FORMATS } from './formats.js';",
  'const __formatsRef = { value: FORMATS };',
  standaloneCode,
  'export { validate as schemaValidate };',
  ''
].join('\n');

const result = await build({
  stdin: {
    contents: entry,
    resolveDir: coreSrc,
    loader: 'ts',
    sourcefile: 'validator-entry.ts'
  },
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  mainFields: ['module', 'main'],
  absWorkingDir: repo,
  target: 'es2022',
  write: false,
  minify: false,
  legalComments: 'none',
  plugins: [
    {
      name: 'keep-formats-external',
      setup(build) {
        build.onResolve({ filter: /^\.\/formats\.js$/ }, (args) => ({
          path: args.path,
          external: true
        }));
      }
    }
  ]
});

const generated = [
  '// Generated by scripts/generate-validator.mjs. Do not edit by hand.',
  '// The validator is precompiled and bundled so the package never calls',
  '// eval() or new Function(), which browsers under strict CSP and Workers forbid.',
  '// @ts-nocheck',
  result.outputFiles[0].text.trimEnd(),
  ''
].join('\n');

if (checkOnly) {
  let current = '';
  try {
    current = await readFile(targetPath, 'utf8');
  } catch {
    // A missing file is stale too.
  }
  if (current !== generated) {
    console.error('packages/core/src/validator.generated.ts is stale. Run pnpm run generate:validator.');
    process.exit(1);
  }
} else {
  await writeFile(targetPath, generated);
}
